#!/usr/bin/env node
// Embed the agent skill (skills/vastitecture-modeling) in the CLI, so `vastitecture skill install` works
// from the single-file bundle. `--check` fails (for CI) when the embedded copy is out of date.
import { readFileSync, readdirSync, statSync, writeFileSync } from "node:fs";
import { join, relative } from "node:path";

const root = new URL("../skills/vastitecture-modeling/", import.meta.url).pathname;
const out = new URL("../packages/cli/src/skill-files.generated.ts", import.meta.url).pathname;
const files = {};
const walk = (d) => {
  for (const n of readdirSync(d).sort()) {
    const p = join(d, n);
    if (statSync(p).isDirectory()) walk(p);
    else files[relative(root, p).split("\\").join("/")] = readFileSync(p, "utf8");
  }
};
walk(root);
const text = `// Generated by scripts/build-skill.mjs from skills/vastitecture-modeling. Do not edit.\nexport const SKILL_NAME = "vastitecture-modeling";\nexport const SKILL_FILES: Record<string, string> = ${JSON.stringify(files, null, 2)};\n`;
if (process.argv.includes("--check")) {
  let current = "";
  try {
    current = readFileSync(out, "utf8");
  } catch {}
  if (current !== text) {
    console.error("packages/cli/src/skill-files.generated.ts is out of date. Run `pnpm skill` and commit the result.");
    process.exit(1);
  }
  console.log(`${Object.keys(files).length} skill files, up to date`);
} else {
  writeFileSync(out, text);
  console.log(`Embedded ${Object.keys(files).length} skill files in ${relative(process.cwd(), out)}`);
}
