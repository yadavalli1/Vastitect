import { presentationType, type ExportResult, type View, type Workspace } from "@vastitecture/core";
import { activate, definePlugin } from "@vastitecture/plugin-sdk";
import { LIGHT, markdownToHtml, viewToSvg } from "@vastitecture/render";
import { writePdf } from "@vastitecture/io-formats";
import { hostServices, registry } from "./plugins";

/**
 * Exporters that need the renderer and the full registry (every installed notation's shapes), so they
 * run in the app rather than in a worker. They still register through the plugin API.
 */
const slug = (s: string) => s.toLowerCase().replace(/[^a-z0-9]+/g, "-").replace(/^-|-$/g, "") || "view";
const esc = (s: unknown) => String(s ?? "").replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;").replace(/"/g, "&quot;");
const mdCell = (s: unknown) => String(s ?? "").replace(/\|/g, "\\|").replace(/\n/g, " ");

const orderedViews = (ws: Workspace) => Object.values(ws.views).filter((v) => v.nodes.length || v.annotations.length).sort((a, b) => a.notation.localeCompare(b.notation) || a.name.localeCompare(b.name));
const svgOf = (ws: Workspace, v: View) => viewToSvg(ws, v, registry, LIGHT);
const typeName = (ws: Workspace, v: View, id: string) => {
  const e = ws.elements[id];
  return registry.elementType(presentationType(ws, e, v.notation, registry) ?? e.type)?.name ?? e.type;
};

async function rasterise(svg: string, maxSide = 2400): Promise<{ jpeg: Uint8Array; width: number; height: number }> {
  const img = new Image();
  const url = URL.createObjectURL(new Blob([svg], { type: "image/svg+xml" }));
  await new Promise<void>((res, rej) => ((img.onload = () => res()), (img.onerror = () => rej(new Error("Could not render the view")), (img.src = url))));
  const scale = Math.min(2, maxSide / Math.max(img.width, img.height));
  const canvas = document.createElement("canvas");
  canvas.width = Math.max(1, Math.round(img.width * scale));
  canvas.height = Math.max(1, Math.round(img.height * scale));
  const ctx = canvas.getContext("2d")!;
  ctx.fillStyle = "#fff";
  ctx.fillRect(0, 0, canvas.width, canvas.height);
  ctx.drawImage(img, 0, 0, canvas.width, canvas.height);
  URL.revokeObjectURL(url);
  const blob = await new Promise<Blob>((res, rej) => canvas.toBlob((b) => (b ? res(b) : rej(new Error("JPEG encoding failed"))), "image/jpeg", 0.92));
  return { jpeg: new Uint8Array(await blob.arrayBuffer()), width: canvas.width, height: canvas.height };
}

const STYLE = `body{font:15px/1.5 system-ui,sans-serif;max-width:1100px;margin:0 auto;padding:24px;color:#0f172a}a{color:#1d4ed8}nav a{margin-right:14px}
table{border-collapse:collapse;width:100%;margin:12px 0}th,td{border:1px solid #cbd5e1;padding:4px 8px;text-align:left;vertical-align:top}th{background:#f1f5f9}
figure{margin:16px 0;border:1px solid #e2e8f0;overflow:auto}figure svg{max-width:100%;height:auto}.muted{color:#64748b}code{background:#f1f5f9;padding:0 3px}`;
const page = (title: string, body: string, depth = 0) => {
  const up = depth ? "../" : "";
  return `<!doctype html>\n<html lang="en"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1"><title>${esc(title)}</title><style>${STYLE}</style></head>\n<body><nav><a href="${up}index.html">Overview</a><a href="${up}elements.html">Elements</a><a href="${up}decisions.html">Decisions</a></nav>\n${body}\n<p class="muted">Generated by Vastitecture. ArchiMate® and TOGAF® are registered trademarks of The Open Group.</p></body></html>\n`;
};

function site(ws: Workspace): Record<string, string> {
  const files: Record<string, string> = {};
  const views = orderedViews(ws);
  const names = new Map<string, string>();
  for (const v of views) {
    let s = slug(v.name);
    for (let i = 2; [...names.values()].includes(s); i++) s = `${slug(v.name)}-${i}`;
    names.set(v.id, s);
  }
  const byNotation = new Map<string, View[]>();
  for (const v of views) byNotation.set(v.notation, [...(byNotation.get(v.notation) ?? []), v]);
  files["index.html"] = page(
    ws.name,
    `<h1>${esc(ws.name)}</h1><p class="muted">${Object.keys(ws.elements).length} elements · ${Object.keys(ws.relationships).length} relationships · ${views.length} views</p>` +
      [...byNotation].map(([n, list]) => `<h2>${esc(registry.packs.get(n)?.name ?? n)}</h2><ul>${list.map((v) => `<li><a href="views/${names.get(v.id)}.html">${esc(v.name)}</a>${v.description ? ` <span class="muted">— ${esc(v.description)}</span>` : ""}</li>`).join("")}</ul>`).join(""),
  );
  for (const v of views) {
    const rows = v.nodes.filter((n) => ws.elements[n.element]).map((n) => ws.elements[n.element]).sort((a, b) => a.name.localeCompare(b.name));
    files[`views/${names.get(v.id)}.html`] = page(
      v.name,
      `<h1>${esc(v.name)}</h1><p class="muted">${esc(registry.viewpoint(v.notation, v.viewpoint)?.name ?? registry.packs.get(v.notation)?.name ?? v.notation)}</p>${v.description ? `<p>${esc(v.description)}</p>` : ""}<figure>${svgOf(ws, v).replace(/^<svg /, '<svg role="img" ')}</figure>` +
        `<h2>Elements</h2><table><tr><th>Name</th><th>Type</th><th>Description</th><th>Owner</th></tr>${rows.map((e) => `<tr><td><a href="../elements.html#${e.id}">${esc(e.name)}</a></td><td>${esc(typeName(ws, v, e.id))}</td><td>${esc(e.description)}</td><td>${esc(e.owner)}</td></tr>`).join("")}</table>`,
      1,
    );
    files[`views/${names.get(v.id)}.svg`] = svgOf(ws, v);
  }
  const shownIn = (id: string) => views.filter((v) => v.nodes.some((n) => n.element === id));
  const els = Object.values(ws.elements).sort((a, b) => a.name.localeCompare(b.name));
  files["elements.html"] = page(
    `${ws.name}: elements`,
    `<h1>Elements</h1><table><tr><th>Name</th><th>Type</th><th>Description</th><th>Owner</th><th>Lifecycle</th><th>Shown in</th></tr>${els
      .map((e) => `<tr id="${e.id}"><td>${esc(e.name)}${e.links.map((l) => ` <a href="${esc(/^https?:/.test(l.href) ? l.href : "#")}">${esc(l.kind)}</a>`).join("")}</td><td>${esc(registry.elementType(e.type)?.name ?? e.type)}</td><td>${esc(e.description)}</td><td>${esc(e.owner)}</td><td>${esc(e.lifecycle?.phase)}</td><td>${shownIn(e.id).map((v) => `<a href="views/${names.get(v.id)}.html">${esc(v.name)}</a>`).join(", ")}</td></tr>`)
      .join("")}</table>`,
  );
  const adrs = Object.values(ws.adrs).sort((a, b) => a.id.localeCompare(b.id));
  files["decisions.html"] = page(`${ws.name}: decisions`, `<h1>Architecture decisions</h1>${adrs.map((a) => `<section id="adr-${esc(a.id)}"><h2>${esc(a.id)} ${esc(a.title)}</h2><p class="muted">${esc(a.status)}${a.date ? ` · ${esc(a.date)}` : ""}${a.elements.length ? ` · ${a.elements.map((id) => ws.elements[id]).filter(Boolean).map((e) => `<a href="elements.html#${e.id}">${esc(e.name)}</a>`).join(", ")}` : ""}</p>${markdownToHtml(a.body)}</section>`).join("") || '<p class="muted">No decisions recorded yet.</p>'}`);
  return files;
}

function markdownDocs(ws: Workspace): Record<string, string> {
  const files: Record<string, string> = {};
  const views = orderedViews(ws);
  const out = [`# ${ws.name}`, "", `${Object.keys(ws.elements).length} elements, ${Object.keys(ws.relationships).length} relationships, ${views.length} views.`, ""];
  for (const v of views) {
    const s = slug(v.name);
    files[`views/${s}.svg`] = svgOf(ws, v);
    out.push(`## ${v.name}`, "", `*${registry.viewpoint(v.notation, v.viewpoint)?.name ?? registry.packs.get(v.notation)?.name ?? v.notation}*`, "");
    if (v.description) out.push(v.description, "");
    out.push(`![${v.name}](views/${s}.svg)`, "", "| Element | Type | Description |", "| --- | --- | --- |");
    for (const n of v.nodes) if (ws.elements[n.element]) out.push(`| ${mdCell(ws.elements[n.element].name)} | ${mdCell(typeName(ws, v, n.element))} | ${mdCell(ws.elements[n.element].description)} |`);
    out.push("");
  }
  files["README.md"] = out.join("\n");
  for (const a of Object.values(ws.adrs)) files[`decisions/${a.id}-${slug(a.title)}.md`] = `# ${a.id}. ${a.title}\n\nStatus: ${a.status}${a.date ? `\nDate: ${a.date}` : ""}\n\n${a.body}\n`;
  return files;
}

export const hostExporters = definePlugin({
  manifest: { id: "vastitecture.host-exporters", name: "PDF and documentation site", version: "0.1.0", apiVersion: "1.0.0", capabilities: ["exporter"] },
  activate(ctx) {
    ctx.exporters.register({
      id: "pdf-view",
      label: "PDF (this view)",
      extension: "pdf",
      scope: "view",
      async export(ws, o): Promise<ExportResult> {
        const v = ws.views[o.view!];
        return writePdf([await rasterise(svgOf(ws, v))], { title: v.name });
      },
    });
    ctx.exporters.register({
      id: "pdf",
      label: "PDF (all views)",
      extension: "pdf",
      scope: "workspace",
      async export(ws): Promise<ExportResult> {
        const pages = [];
        for (const v of orderedViews(ws)) pages.push(await rasterise(svgOf(ws, v)));
        return writePdf(pages, { title: ws.name });
      },
    });
    ctx.exporters.register({ id: "site", label: "Static HTML site", extension: "zip", scope: "workspace", export: (ws) => site(ws) });
    ctx.exporters.register({ id: "markdown", label: "Markdown documentation", extension: "zip", scope: "workspace", export: (ws) => markdownDocs(ws) });
  },
});

export const activateHostExporters = () => activate(hostExporters, registry, hostServices);
